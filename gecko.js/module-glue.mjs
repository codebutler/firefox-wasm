// Convert the linked classic MODULARIZE runtime into an importable module.
// Kept as a build step because this emsdk's EXPORT_ES6 pthread bootstrap is
// unreliable. The factory and pthread entry share compiled code, never eval.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export function moduleGlue(source) {
  if (!source.includes('var createGecko =')) throw new Error('Missing Gecko factory');
  const tail = 'isPthread && createGecko();';
  if (!source.includes(tail)) throw new Error('Missing Gecko pthread entry');
  const nodeCheck = 'var ENVIRONMENT_IS_NODE = globalThis.process?.versions?.node && globalThis.process?.type != "renderer";';
  if (!source.includes(nodeCheck)) throw new Error('Missing Gecko environment check');
  source = source.replace(nodeCheck, 'var ENVIRONMENT_IS_NODE = false;');
  const worker = 'new Worker(pthreadMainJs, {';
  if (!source.includes(worker)) throw new Error('Missing Gecko worker constructor');
  source = source.replace(worker, worker + '\n      type: "module",');
  return `// Generated by module-glue.mjs; do not edit.
const process = undefined, module = undefined, exports = undefined;
${source.replace(tail, '')}
export default createGecko;
export function startPthread() { return createGecko(); }
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(new URL('./dist/', import.meta.url), { recursive: true });
  const input = new URL('./wasm/gecko.js', import.meta.url);
  writeFileSync(new URL('./wasm/gecko-engine.mjs', import.meta.url), moduleGlue(readFileSync(input, 'utf8')));
  writeFileSync(new URL('./dist/gecko-pthread.mjs', import.meta.url),
    "import { startPthread } from './gecko-engine.mjs';\nstartPthread();\n");
}
